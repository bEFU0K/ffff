    private static func flag(_ iso: String) -> String {
        var result = ""
        for scalar in iso.unicodeScalars {
            if let s = UnicodeScalar(127397 + scalar.value) {
                result.unicodeScalars.append(s)
            }
        }
        return result
    }

    private static func digits(_ phone: String) -> String {
        return String(phone.filter { $0 >= "0" && $0 <= "9" })
    }

    /// Страна по номеру (с флагом). Работает, если номер виден клиенту.
    public static func country(phone: String?) -> String? {
        guard let phone = phone else { return nil }
        let number = digits(phone)
        if number.isEmpty { return nil }
        if number.hasPrefix("888") { return "Анонимный номер (Fragment)" }
        if number.hasPrefix("1") {
            let area = number.count >= 4 ? String(number.dropFirst().prefix(3)) : ""
            if canadaAreaCodes.contains(area) { return flag("CA") + " Канада" }
            return flag("US") + " США"
        }
        for len in [3, 2, 1] where number.count >= len {
            if let entry = codes[String(number.prefix(len))] {
                return flag(entry.0) + " " + entry.1
            }
        }
        return nil
    }

    public static func infoText(for user: TelegramUser) -> String {
        var parts = ["ID: \(user.id.id._internalGetInt64Value())"]
        if let c = country(phone: user.phone) { parts.append(c) }
        return parts.joined(separator: " · ")
    }
